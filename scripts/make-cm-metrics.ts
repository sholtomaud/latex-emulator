/**
 * Generate src/latex/listings/cm-metrics.ts: Computer Modern advance widths,
 * heights and depths (printable ASCII, OT1 slots; OML for cmmi), quad and
 * interword space, in em, from TeX Live's TFM files via tftopl. Latin
 * Modern has the same metrics. listings needs the widths for flexible
 * columns (\lst@lostspace) and basewidth's em; algorithms need heights and
 * depths, where a rule stops interline glue (ADR 0016).
 *
 *   node scripts/make-cm-metrics.ts
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const FONTS = {
  rm: 'cmr10',
  bf: 'cmbx10',
  it: 'cmti10',
  sl: 'cmsl10',
  bfit: 'cmbxti10',
  sf: 'cmss10',
  tt: 'cmtt10',
  sc: 'cmcsc10',
  mi: 'cmmi10',
} as const;

function metrics(tfm: string) {
  const path = execFileSync('kpsewhich', [`${tfm}.tfm`], {
    encoding: 'utf8',
  }).trim();
  const pl = execFileSync('tftopl', [path], { encoding: 'utf8' });
  const param = (name: string) =>
    Number(new RegExp(`\\(${name} R ([-\\d.]+)\\)`).exec(pl)![1]);
  const widths: number[] = [];
  const heights: number[] = [];
  const depths: number[] = [];
  const round = (v: string | undefined) => Number(Number(v ?? 0).toFixed(4));
  for (const block of pl.split('\n(CHARACTER ').slice(1)) {
    const m = /^(?:C (\S)|O (\d+))/.exec(block)!;
    const code = m[1] !== undefined ? m[1].charCodeAt(0) : parseInt(m[2], 8);
    if (code < 32 || code > 126) continue;
    const field = (name: string) =>
      new RegExp(`\\(${name} R ([-\\d.]+)\\)`).exec(block)?.[1];
    widths[code - 32] = round(field('CHARWD'));
    heights[code - 32] = round(field('CHARHT'));
    depths[code - 32] = round(field('CHARDP'));
  }
  return {
    quad: Number(param('QUAD').toFixed(4)),
    space: Number(param('SPACE').toFixed(4)),
    widths: Array.from({ length: 95 }, (_, i) => widths[i] ?? 0),
    heights: Array.from({ length: 95 }, (_, i) => heights[i] ?? 0),
    depths: Array.from({ length: 95 }, (_, i) => depths[i] ?? 0),
  };
}

const out = Object.fromEntries(
  Object.entries(FONTS).map(([k, f]) => [k, metrics(f)])
);
writeFileSync(
  new URL('../src/latex/listings/cm-metrics.ts', import.meta.url),
  `/**
 * Generated by scripts/make-cm-metrics.ts from the Computer Modern TFM files
 * (cmr10, cmbx10, cmti10, cmsl10, cmbxti10, cmss10, cmtt10, cmcsc10; cmmi10,
 * OML). Widths, heights and depths of slots 32–126, in em. Do not edit.
 */
export interface CmMetrics {
  /** \\fontdimen6: what TeX's em is. */
  quad: number;
  /** \\fontdimen2: the interword space. */
  space: number;
  /** Advance widths of slots 32–126. */
  widths: number[];
  /** Heights above the baseline of slots 32–126. */
  heights: number[];
  /** Depths below the baseline of slots 32–126. */
  depths: number[];
}

export const CM_METRICS: Record<string, CmMetrics> = ${JSON.stringify(out)};
`
);
console.log('wrote', Object.keys(out).join(', '));
